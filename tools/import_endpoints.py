#!/usr/bin/env python3
"""Import routing facts from the Python reference, without executing its code.

Usage: python3 tools/import_endpoints.py /path/to/renault_api/kamereon/models.py
The generated Rust and matrix fixture are self-contained at runtime.
"""

import ast
import hashlib
import json
import pathlib
import sys

source = pathlib.Path(sys.argv[1])
root = pathlib.Path(__file__).resolve().parents[1]
tables = {}


def value(node):
    if isinstance(node, ast.Constant):
        return node.value
    if isinstance(node, ast.Dict):
        return {value(k): value(v) for k, v in zip(node.keys, node.values)}
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "EndpointDefinition":
        return {"path": value(node.args[0]), "mode": next((value(k.value) for k in node.keywords if k.arg == "mode"), "default")}
    if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name):
        return tables[node.value.id][value(node.slice)]
    raise ValueError(f"Unsupported routing expression: {ast.dump(node)}")


for node in ast.parse(source.read_text()).body:
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        name = node.target.id
        if name in ("_DEFAULT_ENDPOINTS", "_KCA_ALTERNATIVE_ENDPOINTS", "_KCM_ENDPOINTS", "_VEHICLE_ENDPOINTS"):
            tables[name] = value(node.value)

defaults = tables["_DEFAULT_ENDPOINTS"]
models = tables["_VEHICLE_ENDPOINTS"]


def variant(name):
    return "".join(part.capitalize() for part in name.replace("actions/", "set-").split("-"))


def mode(name):
    return {"default": "Default", "kca-stop": "KcaStop", "kcm": "Kcm", "kcm-pause-resume": "KcmPauseResume", "kcm-settings": "KcmSettings"}[name]


def definition(d):
    return f'EndpointDefinition {{ path: {json.dumps(d["path"])}, mode: EndpointMode::{mode(d["mode"])} }}'


lines = [
    "//! Routing facts adapted from hacf-fr/renault-api (MIT, copyright 2020 epenet).",
    "//! Generated by tools/import_endpoints.py; do not edit the table by hand.",
    f'//! Reference SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}',
    "use serde::{Deserialize, Serialize};",
    "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Deserialize, Serialize)]",
    "pub enum Endpoint {",
]
for name in defaults:
    lines.extend([f'    #[serde(rename = {json.dumps(name)})]', f"    {variant(name)},"])
lines.extend(["}", "#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]", "pub enum EndpointMode { Default, KcaStop, Kcm, KcmPauseResume, KcmSettings }", "#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]", "pub struct EndpointDefinition { pub path: &'static str, pub mode: EndpointMode }", "impl Endpoint {", "    pub const ALL: &'static [Self] = &["])
lines.extend(f"        Self::{variant(name)}," for name in defaults)
lines.extend(["    ];", "    pub const fn as_str(self) -> &'static str { match self {"])
lines.extend(f"        Self::{variant(name)} => {json.dumps(name)}," for name in defaults)
lines.extend(["    }}", "    /// Unknown models/endpoints use the reference defaults, not a guarantee of support.", "    pub fn definition_for_model(self, model: Option<&str>) -> Option<EndpointDefinition> {", "        match (model, self) {"])
for model, overrides in models.items():
    for name, d in overrides.items():
        if name in defaults and d != defaults[name]:
            result = "None" if d is None else f"Some({definition(d)})"
            lines.append(f"            (Some({json.dumps(model)}), Self::{variant(name)}) => {result},")
lines.extend(["            _ => Some(match self {"])
lines.extend(f"                Self::{variant(name)} => {definition(d)}," for name, d in defaults.items())
lines.extend(["            }),", "        }", "    }", "}"])
(root / "src/endpoints.rs").write_text("\n".join(lines) + "\n")
matrix = {model: {name: overrides.get(name, default) for name, default in defaults.items()} for model, overrides in models.items()}
matrix["UNKNOWN"] = defaults
(root / "tests/fixtures/endpoint_matrix.json").write_text(json.dumps(matrix, indent=2) + "\n")
print(f"Imported {len(defaults)} endpoints and {len(models)} model tables.")
